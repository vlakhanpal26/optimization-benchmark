# /solvers/highs_runner.py
"""
Run a .lp model with HiGHS and capture basic metrics.
Part of the benchmark framework.

Interface:
    from solvers.highs_runner import solve_lp
    res = solve_lp(lp_path, time_limit=600)

The function returns a dict that is JSON-serialised to
data/results/highs_<stem>.json, and it also saves the raw
HiGHS log to highs_<stem>.log for later parsing.
"""

import os, json, time
from pathlib import Path
from datetime import datetime
import highspy                         # official HiGHS API

# ------------------------------------------------------------------
ROOT = Path(os.environ["BENCHMARK_ROOT"]).resolve()
RES_DIR = ROOT / "data" / "results"
RES_DIR.mkdir(parents=True, exist_ok=True)
# ------------------------------------------------------------------


def solve_lp(lp_file: Path, time_limit: int = 600):
    """
    Parameters
    ----------
    lp_file : Path
        Full path to a .lp file generated by problems.facility_location.
    time_limit : int
        Seconds before the solver stops (HiGHS option "time_limit").

    Returns
    -------
    dict
        Keys: solver, model, status, obj, time_sec, nodes.
    """

    model_name = lp_file.stem
    solver_name = "HiGHS"

    # ---------- set up HiGHS ----------
    highs = highspy.Highs()
    highs.readModel(str(lp_file))

    highs.setOptionValue("time_limit", time_limit)
    # Write full log to a file
    log_path = RES_DIR / f"{solver_name.lower()}_{model_name}.log"
    highs.setOptionValue("log_file", str(log_path))

    # less noisy screen output
    highs.setOptionValue("output_flag", True)

    # ---------- solve ----------
    t0 = time.perf_counter()
    status = highs.run()
    t1 = time.perf_counter()

    info = highs.getInfo()
    obj   = info.objective_function_value
    nodes = getattr(info, "mip_node_count", 0)      # 0 for pure LP

    result = {
        "solver"   : solver_name,
        "model"    : model_name,
        "status"   : str(status),
        "objective": obj,
        "time_sec" : t1 - t0,
        "nodes"    : nodes,
        "log_file" : str(log_path.relative_to(ROOT))
    }

    # ---------- persist JSON ----------
    json_path = RES_DIR / f"{solver_name.lower()}_{model_name}.json"
    with open(json_path, "w") as f:
        json.dump(result, f, indent=2)

    print(f"✅ {solver_name}: {model_name} solved in {result['time_sec']:.2f}s – status {status}")
    return result


# ---------- quick CLI for ad-hoc tests ---------------------------
if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("lp_file", help="Path to .lp model")
    ap.add_argument("--time_limit", type=int, default=600)
    args = ap.parse_args()

    solve_lp(Path(args.lp_file), args.time_limit)
